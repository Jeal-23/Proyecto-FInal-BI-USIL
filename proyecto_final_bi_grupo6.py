# 5. CORRELACIÓN POR CO-OCURRENCIA EN TICKET — MEJORADA
#    v1.0: pivot por fecha → detecta tendencias de época, no afinidad de compra
#    v2.0: pivot por N° Documento → detecta productos comprados JUNTOS
# ─────────────────────────────────────────────────────────────────────────────
def correlacion_tickets(sub_df, nombre_tienda, top_n=8):
    """
    Genera matriz de correlación por co-ocurrencia en el mismo ticket
    de compra (N° Documento), no por fecha.
    Una correlación alta = esos productos tienden a comprarse juntos.
    """
    # Solo ventas positivas (excluir devoluciones)
    sub_ventas = sub_df[sub_df['Total Venta'] > 0].copy()

    if sub_ventas.empty:
        print(f"\n{'─'*55}")
        print(f"CORRELACIÓN POR TICKET — {nombre_tienda}")
        print(f"{'─'*55}")
        print(f"  No hay datos de ventas para calcular la correlación para {nombre_tienda}.")
        return pd.DataFrame(), []

    top_prods = (
        sub_ventas
        .groupby('Descripción Material')['Total Venta']
        .sum()
        .nlargest(top_n)
        .index
    )

    if top_prods.empty:
        print(f"\n{'─'*55}")
        print(f"CORRELACIÓN POR TICKET — {nombre_tienda}")
        print(f"{'─'*55}")
        print(f"  No se encontraron productos top para calcular la correlación para {nombre_tienda}.")
        return pd.DataFrame(), []

    # CORRECCIÓN CLAVE: pivot por ticket, no por fecha
    pivot = (
        sub_ventas[sub_ventas['Descripción Material'].isin(top_prods)]
        .pivot_table(
            index='N° Documento',          # \u2190 cada fila = un ticket
            columns='Descripción Material',
            values='Cantidad',
            aggfunc='sum'
        )
        .fillna(0)
    )

    if pivot.empty or len(pivot.columns) < 2: # Necesita al menos 2 columnas para correlación
        print(f"\n{'─'*55}")
        print(f"CORRELACIÓN POR TICKET — {nombre_tienda}")
        print(f"{'─'*55}")
        print(f"  No hay suficientes productos únicos o transacciones para calcular la correlación para {nombre_tienda}.")
        return pd.DataFrame(), []

    correlacion = pivot.corr()

    print(f"\n{'─'*55}")
    print(f"CORRELACIÓN POR TICKET — {nombre_tienda}")
    print(f"{'─'*55}")
    # Mostrar los pares con mayor afinidad (excluyendo diagonal)
    mask = np.triu(np.ones(correlacion.shape), k=1).astype(bool)
    pares = (
        correlacion.where(mask)
        .stack()
        .rename_axis(index=['Producto A', 'Producto B']) # Name the index levels
        .reset_index(name='Correlación') # Reset index and name the value column
        .sort_values('Correlación', ascending=False)
        .head(5)
    )
    print(pares.to_string(index=False))
    print("\n  \u2192 Pares con correlación alta: oportunidades de cross-selling.")

    return correlacion, top_prods

