# 3. TEST DE STUDENT —  (granularidad diaria por tienda)
#
# ─────────────────────────────────────────────────────────────────────────────
def test_student_tienda(sub_df, nombre_tienda):
    """
    Agrega ventas por día y compara 'días de pago' (1-5 y 28-31)
    contra días normales usando t-test de Welch (equal_var=False).
    """
    # Agregación diaria — CORRECCIÓN CLAVE respecto a v1.0
    diario = sub_df.groupby('Fecha')['Total Venta'].sum().reset_index()
    diario['Es_Pago'] = diario['Fecha'].dt.day.apply(
        lambda x: 'Pago' if x <= 5 or x >= 28 else 'Normal'
    )

    grupo_pago   = diario[diario['Es_Pago'] == 'Pago']['Total Venta']
    grupo_normal = diario[diario['Es_Pago'] == 'Normal']['Total Venta']

    # Manejo de casos sin datos para evitar errores
    if grupo_pago.empty or grupo_normal.empty:
        t_stat, p_valor = np.nan, np.nan
        media_pago, media_normal = np.nan, np.nan
        diferencia, efecto_pct = np.nan, np.nan
    else:
        # Welch t-test
        t_stat, p_valor = stats.ttest_ind(grupo_pago, grupo_normal, equal_var=False)

        media_pago   = grupo_pago.mean()
        media_normal = grupo_normal.mean()
        diferencia   = media_pago - media_normal
        efecto_pct   = (diferencia / media_normal * 100) if media_normal > 0 else 0

    print(f"\n{'─'*55}")
    print(f"TEST DE STUDENT — {nombre_tienda}")
    print(f"{'─'*55}")
    print(f"  Días de pago   : n={len(grupo_pago)}, media S/ {media_pago:,.2f}")
    print(f"  Días normales  : n={len(grupo_normal)}, media S/ {media_normal:,.2f}")
    print(f"  Diferencia     : S/ {diferencia:,.2f}  ({efecto_pct:+.1f}%)")
    print(f"  t-estadístico  : {t_stat:.4f}")
    print(f"  p-valor        : {p_valor:.4f}")
    if pd.isna(p_valor) or p_valor >= 0.05:
        print(f"  → NO significativo (p\u22650.05): consumo estable a lo largo del mes.")
    else:
        print(f"  → SIGNIFICATIVO (p<0.05): reforzar stock y personal en fechas de pago.")

    return diario, grupo_pago, grupo_normal, t_stat, p_valor, media_pago, media_normal

