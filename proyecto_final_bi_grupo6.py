# 4. REGRESIÓN LINEAL — (R², RMSE, pendiente, IC 95%, por tienda)
#
# ─────────────────────────────────────────────────────────────────────────────
def regresion_tienda(sub_df, nombre_tienda, dias_futuro=7):
    diario = sub_df.groupby('Fecha')['Total Venta'].sum().reset_index()

    # Manejo de casos sin datos para evitar errores de regresión
    if diario.empty or len(diario) < 2: # Necesita al menos 2 puntos para la regresión
        print(f"\n{'─'*55}")
        print(f"REGRESIÓN LINEAL — {nombre_tienda}")
        print(f"{'─'*55}")
        print(f"  No hay suficientes datos para realizar la regresión lineal para {nombre_tienda}.")
        print(f"  (Se requieren al menos 2 días de datos de ventas. Se encontraron {len(diario)}).")
        # Devolver valores por defecto o NaN para evitar errores posteriores
        return pd.DataFrame(), None, np.array([]), np.array([]), np.array([]), np.array([]), [], np.nan, np.nan, np.nan

    diario['Dia_Num'] = np.arange(len(diario))

    X = diario[['Dia_Num']].values
    y = diario['Total Venta'].values

    modelo = LinearRegression().fit(X, y)
    y_pred  = modelo.predict(X)

    r2   = r2_score(y, y_pred)
    rmse = np.sqrt(mean_squared_error(y, y_pred))
    pendiente = modelo.coef_[0]
    intercepto = modelo.intercept_

    # Intervalo de confianza 95% (aproximación por residuos)
    n = len(y)
    # Solo calcular IC si n > 2 para evitar división por cero en df=n-2
    if n > 2:
        residuos = y - y_pred
        se = np.sqrt(np.sum(residuos**2) / (n - 2))
        t_crit = stats.t.ppf(0.975, df=n-2)
        x_mean = X.mean()
        # Calcular IC solo si el denominador no es cero
        denominator = np.sum((X.flatten() - x_mean)**2)
        if denominator > 0:
            ic = t_crit * se * np.sqrt(1/n + (X.flatten() - x_mean)**2 / denominator)
        else:
            ic = np.zeros_like(y_pred)
    else:
        ic = np.zeros_like(y_pred) # No se puede calcular IC con pocos datos

    # Predicción próximos días
    proximos_X = np.array([[len(diario) + i] for i in range(1, dias_futuro + 1)])
    predicciones = modelo.predict(proximos_X)
    fechas_futuras = [diario['Fecha'].max() + pd.Timedelta(days=i) for i in range(1, dias_futuro + 1)]

    print(f"\n{'─'*55}")
    print(f"REGRESIÓN LINEAL — {nombre_tienda}")
    print(f"{'─'*55}")
    print(f"  R²        : {r2:.4f}  {'(buen ajuste)' if r2 > 0.4 else '(ajuste débil — esperado con datos cortos)'}")
    print(f"  RMSE      : S/ {rmse:,.2f}")
    print(f"  Pendiente : S/ {pendiente:+.2f} / día  {'(tendencia CRECIENTE \u2191)' if pendiente > 0 else '(tendencia DECRECIENTE \u2193)'}")
    print(f"\n  Proyección {dias_futuro} días:")
    for fecha, pred in zip(fechas_futuras, predicciones):
        print(f"    {fecha.strftime('%d/%m/%Y')} : S/ {pred:,.2f}")

    return diario, modelo, y_pred, ic, proximos_X, predicciones, fechas_futuras, r2, rmse, pendiente

