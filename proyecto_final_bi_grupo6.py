def kpis_tienda(sub_df, nombre):
    ventas_netas  = sub_df['Total Venta'].sum()
    ventas_brutas = sub_df[sub_df['Total Venta'] > 0]['Total Venta'].sum()
    devoluciones  = abs(sub_df[sub_df['Total Venta'] < 0]['Total Venta'].sum())
    n_transacc    = sub_df['N° Documento'].nunique()
    unidades_netas = sub_df['Cantidad'].sum()
    ticket_prom   = ventas_netas / n_transacc if n_transacc > 0 else 0
    upt           = unidades_netas / n_transacc if n_transacc > 0 else 0
    tasa_devol    = (devoluciones / ventas_brutas * 100) if ventas_brutas > 0 else 0
    return {
        'Tienda'           : nombre,
        'Ventas Netas (S/)': round(ventas_netas, 2),
        'Ventas Brutas (S/)': round(ventas_brutas, 2),
        'Devoluciones (S/)': round(devoluciones, 2),
        'Tasa Devolución %': round(tasa_devol, 2),
        'N° Transacciones' : n_transacc,
        'Ticket Promedio'  : round(ticket_prom, 2),
        'UPT'              : round(upt, 2),
    }

